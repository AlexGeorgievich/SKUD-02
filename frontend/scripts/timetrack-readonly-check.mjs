import {mkdir} from 'node:fs/promises';
import {chromium} from '@playwright/test';

const password=process.env.TIMETRACK_TEST_PASSWORD;
if(!password)throw new Error('Set TIMETRACK_TEST_PASSWORD for the local preview account');
const output='test-results/hr-reference';
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const page=await browser.newPage({viewport:{width:1600,height:1000},deviceScaleFactor:1});
await page.goto('http://127.0.0.1:8001/',{waitUntil:'networkidle'});
await page.getByLabel('Пароль').fill(password);
await page.getByRole('button',{name:'Войти в систему →'}).click();
await page.getByRole('button',{name:'План',exact:true}).click();
const tableName=page.locator('.tablewrap .person-link').first();
await tableName.waitFor();
const employeeName=(await tableName.textContent())?.trim();
if(!employeeName)throw new Error('Employee name is missing in the Plan table');
await tableName.click();
const detail=page.getByRole('dialog',{name:new RegExp(`Проверка данных — ${employeeName}`)});
await detail.waitFor();
await detail.getByRole('button',{name:`Открыть кадровую карточку ${employeeName}`}).click();
const card=page.getByRole('dialog',{name:`Кадровая карточка сотрудника ${employeeName}`});
await card.waitFor();
if(await card.getByRole('button',{name:/Сохранить|В архив|Удалить/}).count())throw new Error('TimeTrack card exposes editing actions');
await page.screenshot({path:`${output}/timetrack-readonly-card.png`,fullPage:true});
await page.keyboard.press('Escape');
await card.waitFor({state:'hidden'});
await detail.waitFor();
const focusAfterCard=await page.evaluate(()=>document.activeElement?.getAttribute('aria-label')||document.activeElement?.textContent?.trim());
await page.keyboard.press('Escape');
await detail.waitFor({state:'hidden'});
const focusAfterDetail=await page.evaluate(()=>document.activeElement?.textContent?.trim());
console.log(JSON.stringify({employeeName,focusAfterCard,focusAfterDetail,readOnly:true}));
await browser.close();
